# Needle-card anchors for the Poly Haven pine (pine_tree_01): the real twig mesh (millions of needle triangles) is reduced to
# one anchor per occupied 0.5 m voxel of twig-cluster centres (position, outward direction, size), per variant (a, b, c).
# Output: a TS module (anchors in each node's mesh-local frame) used by pigset.ts to build alpha needle cards on the trunks.
# usage: python3 -I pine_cards.py SRC_DIR OUT_TS
import json, sys, os, numpy as np
from scipy.sparse import coo_matrix
from scipy.sparse.csgraph import connected_components
src, out = sys.argv[1], sys.argv[2]
g = json.load(open(os.path.join(src, 'pine_tree_01.gltf')))
B = np.memmap(os.path.join(src, 'pine_tree_01.bin'), dtype=np.uint8, mode='r')
CT = {5126: (np.float32, 4), 5125: (np.uint32, 4), 5123: (np.uint16, 2)}
NC = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}
def read(ai):
    a = g['accessors'][ai]; bv = g['bufferViews'][a['bufferView']]; dt, sz = CT[a['componentType']]; n = NC[a['type']]
    off = bv.get('byteOffset', 0) + a.get('byteOffset', 0)
    return np.frombuffer(B[off: off + a['count'] * sz * n].tobytes(), dtype=dt).reshape(a['count'], n)
res = {}
for node in g['nodes']:
    if 'mesh' not in node: continue
    name = node['name']; m = g['meshes'][node['mesh']]
    for p in m['primitives']:
        if 'twig' not in g['materials'][p['material']]['name']: continue
        pos = read(p['attributes']['POSITION']).astype(np.float64); idx = read(p['indices']).reshape(-1, 3).astype(np.int64); nv = pos.shape[0]
        e0 = np.concatenate([idx[:, 0], idx[:, 1], idx[:, 2]]); e1 = np.concatenate([idx[:, 1], idx[:, 2], idx[:, 0]])
        nc, lab = connected_components(coo_matrix((np.ones(e0.size, np.int8), (e0, e1)), shape=(nv, nv)), directed=False)
        cnt = np.bincount(lab, minlength=nc).astype(np.float64)
        cen = np.stack([np.bincount(lab, weights=pos[:, i], minlength=nc) for i in range(3)], 1) / cnt[:, None]
        # trunk axis: the median x/z of the low clusters
        ax, az = np.median(cen[:, 0]), np.median(cen[:, 2])
        V = 0.5; key = np.floor(cen / V).astype(np.int64)
        kk = key[:, 0] * 1000003 + key[:, 1] * 1009 + key[:, 2]
        uq, inv, num = np.unique(kk, return_inverse=True, return_counts=True)
        mean = np.stack([np.bincount(inv, weights=cen[:, i]) for i in range(3)], 1) / num[:, None]
        keep = num >= 3
        A = []
        for (x, y, z), n in zip(mean[keep], num[keep]):
            dx, dz = x - ax, z - az; L = np.hypot(dx, dz) or 1.0
            s = float(np.clip(0.55 + 0.045 * np.sqrt(n), 0.6, 1.15))
            A += [round(float(x), 2), round(float(y), 2), round(float(z), 2), round(dx / L, 2), round(dz / L, 2), round(s, 2)]
        res[name] = A
        print(name, 'clusters', nc, 'anchors', int(keep.sum()))
with open(out, 'w') as f:
    f.write('// generated by tools/pine_cards.py from Poly Haven pine_tree_01 (CC0): needle-card anchors [x, y, z, dirX, dirZ, size] per variant\n')
    f.write('// in each variant node\'s mesh-local frame (the twig mesh reduced to one anchor per occupied 0.5 m voxel of twig clusters)\n')
    for k, v in res.items():
        f.write(f'export const {k.replace("pine_tree_01_", "PC_").replace("_LOD0", "").upper()} = {json.dumps(v)};\n')
